static class Ex02_EvenOdd
{
    public static void Run()
    {
        //Main task ODD and EVEN
        //1-20
        for (int x = 0; x < 20; x++)
        {
            if (x % 2 == 0)
            {
                Console.WriteLine($"{x} is even number");
            }
            else
            {
                Console.WriteLine($"{x} is odd number");
            }
        }

        //Variation #1
        
    }
}